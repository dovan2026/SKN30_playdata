"""각 노드가 모델에 전달할 작업 프롬프트."""


def build_plan_task(topic: str) -> str:
    return f"""
주제: {topic}

다음 조건을 만족하는 콘텐츠 계획을 작성하세요.
1. 주제의 최신 동향, 주요 인물, 주목할 만한 뉴스를 우선순위에 둡니다.
2. 대상 독자를 식별하고 그들의 관심사와 어려움을 분석합니다.
3. 소개, 주요 포인트, 행동 촉구를 포함한 상세한 콘텐츠 개요를 만듭니다.
4. 활용할 SEO 키워드와 관련 데이터 또는 참고할 소스를 제안합니다.

결과에는 개요, 독자 분석, SEO 키워드, 참고 리소스가 포함되어야 합니다.
""".strip()


def build_write_task(topic: str, plan: str) -> str:
    return f"""
주제: {topic}

아래 콘텐츠 계획을 바탕으로 블로그 게시물을 작성하세요.

--- 콘텐츠 계획 ---
{plan}
--- 계획 끝 ---

작성 조건:
1. SEO 키워드를 글에 자연스럽게 통합합니다.
2. 각 섹션과 부제목을 매력적이고 명확하게 작성합니다.
3. 매력적인 소개, 통찰력 있는 본문, 요약 결론으로 구성합니다.
4. 객관적 사실과 작성자의 의견을 명확히 구분합니다.
5. 각 섹션은 2~3개 단락으로 구성하고 마크다운 형식으로 작성합니다.
""".strip()


def build_edit_task(topic: str, draft: str) -> str:
    return f"""
주제: {topic}

아래 블로그 초안을 출판 가능한 글로 편집하세요.

--- 초안 ---
{draft}
--- 초안 끝 ---

문법과 표현을 교정하고, 문체와 논리 전개를 통일하며, 주장에는 균형 잡힌
관점이 드러나게 하세요. 원문의 마크다운 구조와 핵심 정보는 유지하세요.
편집 설명을 덧붙이지 말고 완성된 게시물만 출력하세요.
""".strip()


def build_translate_task(topic: str, edited_content: str) -> str:
    return f"""
주제: {topic}

아래 편집된 블로그 게시물을 바탕으로 자연스러운 한국어 콘텐츠를 작성하세요.

--- 편집된 게시물 ---
{edited_content}
--- 게시물 끝 ---

핵심 내용과 중요한 근거를 보존하면서 2개 이상의 단락으로 요약·번역하세요.
전체 분량은 최대 5,000자이며, 별도의 작업 설명 없이 최종 한국어 콘텐츠만
출력하세요.
""".strip()
